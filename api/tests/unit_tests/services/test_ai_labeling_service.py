    @patch('services.ai_labeling_service.db.session')
    def test_bulk_apply_labeling(self, mock_db_session):
        """Test bulk AI labeling application."""
        # Mock messages
        messages = []
        for i in range(3):
            mock_message = MagicMock()
            mock_message.id = f"message-{i}"
            mock_message.answer = "As an AI, I can help you."
            mock_message.model_provider = "openai"
            mock_message.model_id = "gpt-4"
            messages.append(mock_message)
        
        mock_db_session.query.return_value.filter.return_value.all.return_value = messages
        
        # Apply bulk labeling
        results = self.service.bulk_apply_labeling(
            message_ids=["message-0", "message-1", "message-2"],
            batch_size=2
        )
        
        assert results['total_processed'] == 3
        assert results['total_labeled'] == 3
        assert results['total_errors'] == 0
        
        # Verify all messages were labeled
        for message in messages:
            assert message.ai_generated is True
            assert message.ai_model_info is not None
            assert message.content_labels is not None
    
