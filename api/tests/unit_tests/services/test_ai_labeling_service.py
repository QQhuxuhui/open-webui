    def test_all_supported_languages_have_required_keys(self):
        """Test that all supported languages have required label keys."""
        required_keys = ['text_notice', 'media_notice', 'watermark_text', 'warning']
        
        for language in self.service.DEFAULT_LABELS:
            labels = self.service.get_ai_labels(language)
            for key in required_keys:
                assert key in labels, f"Missing key '{key}' in language '{language}'"
                assert labels[key], f"Empty value for key '{key}' in language '{language}'"